-- Account deletion queue: the request table.
--
-- delete-account no longer deletes the auth user inline. It verifies the JWT,
-- revokes Apple, and inserts one row here (idempotent on the app-generated
-- request_id). process_account_deletions() (next migration, run by pg_cron
-- every minute) deletes users whose request is older than the delay and marks
-- the request completed. A lost reply therefore cannot strand a person: the
-- row is already here, and the app's resend with the same request_id finds it.
--
-- The row must OUTLIVE the user (it records that the deletion was asked for
-- and carried out), so there is deliberately NO foreign key to auth.users.
-- It holds ids, timestamps, a retry count and a SQLSTATE code only: no email,
-- no IP, no free text. deletion_guard_test.sql lists it as exempt and pins its
-- columns.

create table public.account_deletion_requests (
  user_id      uuid        not null,          -- no FK: outlives the user on purpose
  request_id   uuid        not null,          -- generated by the app, resent on retry
  requested_at timestamptz not null default now(),
  completed_at timestamptz,
  attempts     int         not null default 0,
  last_error   text,                          -- SQLSTATE only, never sqlerrm
  primary key (user_id, request_id),
  constraint account_deletion_requests_last_error_sqlstate
    check (last_error is null or last_error ~ '^[0-9A-Z]{5}$')
);

comment on table public.account_deletion_requests is
  'Account deletion queue. Written by delete-account (service role), processed by process_account_deletions(). No FK to auth.users: outlives the user. last_error is a SQLSTATE only.';

-- the worker's scan: open requests, oldest first
create index account_deletion_requests_pending_idx
  on public.account_deletion_requests (requested_at)
  where completed_at is null;

alter table public.account_deletion_requests enable row level security;

-- a signed-in user may see their own requests; nobody in the app writes here
create policy "own deletion requests are readable"
  on public.account_deletion_requests
  for select to authenticated
  using (user_id = (select auth.uid()));

revoke all on table public.account_deletion_requests from public, anon, authenticated, service_role;
grant select on table public.account_deletion_requests to authenticated;
-- delete-account: look up, then insert (select + insert, nothing else)
grant select, insert on table public.account_deletion_requests to service_role;
